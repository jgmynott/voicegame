# Builds src/daily-words.js: the fixed, shuffled order of Daily puzzle answers.
# It lives in src/ (bundled into the Worker), not docs/, so the answers are not public files.
import json, os, random, sys
sys.path.insert(0, os.path.dirname(__file__))
from lists import ANIMALS, FOODS, THINGS, PEOPLE, LANDMARKS, SAYINGS

root = os.path.join(os.path.dirname(__file__), "..")
words = json.load(open(os.path.join(root, "docs", "words.json")))

MULTI = set()
for line in open(os.path.join(os.path.dirname(__file__), "build.py")):
    if line.startswith("MULTI = \"\"\""):
        MULTI = set(line.split('"""')[1].split("|"))
def items(s):
    t = s.split(); out = []; i = 0
    while i < len(t):
        for n in (4, 3, 2):
            p = " ".join(t[i:i+n])
            if p in MULTI: out.append(p); i += n; break
        else: out.append(t[i]); i += 1
    return set(out)

base = {
    "Places": set(LANDMARKS.split("|")),
    "Sayings": set(SAYINGS.split("|")),
    "Animals": items(ANIMALS), "Food": items(FOODS), "Things": items(THINGS), "People": items(PEOPLE),
}
pool, seen = [], set()
for cat, levels in words.items():
    for lvl, lst in levels.items():
        for w in lst:
            if w in base.get(cat, ()) and w.lower() not in seen and 3 <= int(lvl) <= 6:
                seen.add(w.lower()); pool.append([w, cat, int(lvl)])
random.Random(20261125).shuffle(pool)
with open(os.path.join(root, "src", "daily-words.js"), "w") as f:
    f.write("// Generated by tools/daily.py. Order of Daily answers: [word, category, syllables].\n")
    f.write("export default " + json.dumps(pool, separators=(",", ":")) + ";\n")
from collections import Counter
print(len(pool), Counter(c for _, c, _ in pool), pool[:12])
